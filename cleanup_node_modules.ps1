[CmdletBinding()]
param(
    [switch]$delete
)

if ($delete) {
    Write-Host "Delete Mode"
}else{
    Write-Host "Confirmation Mode"
}

$limit = (Get-Date).AddDays(-14)

Get-ChildItem . -Recurse -Directory -Filter node_modules | ForEach-Object {

    $nodeModules = $_
    $projectRoot = $_.Parent.FullName

    $latest = Get-ChildItem $projectRoot -Recurse -File |
        Where-Object {
            $_.FullName -notmatch '\\node_modules\\'
        } |
        Sort-Object LastWriteTime -Descending |
        Select-Object -First 1

    if (-not $latest) {
        return
    }

    if ($latest.LastWriteTime -lt $limit) {
        Write-Host "`n* $($nodeModules.FullName)"
        Write-Host "  Project last updated: $($latest.LastWriteTime)"
        if ($delete) {
            Write-Host "→ deleting node_modules"
            Remove-Item $nodeModules.FullName -Recurse -Force
        }
    }
}